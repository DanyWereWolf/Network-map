function normalizeQuery(text) {
    return String(text || '')
        .toLowerCase()
        .replace(/[^0-9a-zA-Z\u0400-\u04FF\s?]/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

function expandQuickReplyLabel(label) {
    var key = normalizeQuery(label);
    if (QUICK_REPLY_ALIASES[key]) return QUICK_REPLY_ALIASES[key];
    return String(label || '').trim();
}

function tokenize(query) {
    return normalizeQuery(query).split(' ').filter(function(w) {
        return w.length > 1 && !STOP_WORDS[w];
    });
}

function scoreEntry(query, tokens, entry) {
    var score = 0;
    var hits = 0;
    entry.keys.forEach(function(k) {
        if (query.indexOf(k) !== -1) {
            score += k.length;
            hits += 1;
            tokens.forEach(function(t) {
                if (t === k || (t.length >= 3 && (t.indexOf(k) !== -1 || k.indexOf(t) !== -1))) {
                    score += 3;
                }
            });
        }
    });
    if (hits > 1) score += hits * 5;
    return score;
}

function rankEntries(query) {
    var q = normalizeQuery(query);
    if (!q) return [];
    var tokens = tokenize(query);
    return FAQ_ENTRIES.map(function(entry) {
        return { entry: entry, score: scoreEntry(q, tokens, entry) };
    }).filter(function(r) { return r.score > 0; })
      .sort(function(a, b) { return b.score - a.score; });
}

function uniqueQuickReplies(items, limit) {
    var seen = {};
    var out = [];
    (items || []).forEach(function(item) {
        var s = String(item || '').trim();
        if (!s || seen[s]) return;
        seen[s] = true;
        out.push(s);
    });
    return out.slice(0, limit || 4);
}

function matchFaq(query) {
    var q = normalizeQuery(query);
    if (!q) {
        return { answer: DEFAULT_ANSWER, matched: false, quickReplies: getQuickReplies() };
    }

    var aliasExpanded = expandQuickReplyLabel(query);
    if (aliasExpanded !== String(query || '').trim()) {
        return matchFaq(aliasExpanded);
    }

    var ranked = rankEntries(query);
    if (ranked.length === 0) {
        return { answer: DEFAULT_ANSWER, matched: false, quickReplies: getQuickReplies() };
    }

    var best = ranked[0];
    if (best.score > 0) {
        var answer = best.entry.answer;
        if (ranked.length > 1 && ranked[1].score >= best.score * 0.85) {
            answer += ' Кстати, ещё может пригодиться тема «' + ranked[1].entry.hint + '».';
        }
        return {
            answer: answer,
            matched: true,
            topicId: best.entry.id,
            quickReplies: uniqueQuickReplies(
                (best.entry.quickReplies || []).concat(DEFAULT_QUICK_REPLIES),
                4
            )
        };
    }

    return { answer: DEFAULT_ANSWER, matched: false, quickReplies: getQuickReplies() };
}

function getQuickReplies() {
    return DEFAULT_QUICK_REPLIES.slice();
}

module.exports = {
    matchFaq: matchFaq,
    getQuickReplies: getQuickReplies,
    expandQuickReplyLabel: expandQuickReplyLabel
};
