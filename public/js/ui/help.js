function setupHelpModalHandlers() {
    var closeBtn = document.querySelector('.close-help');
    if (closeBtn) closeBtn.addEventListener('click', closeHelpModal);
    var modal = document.getElementById('helpModal');
    if (modal) modal.addEventListener('click', function(e) {
        if (e.target === modal) {
            closeHelpModal();
            return;
        }
        if (e.target && e.target.id === 'helpStartOnboardingBtn') {
            closeHelpModal();
            if (typeof window.restartOnboardingTour === 'function') {
                setTimeout(function() { window.restartOnboardingTour(); }, 120);
            } else if (typeof window.startOnboardingTour === 'function') {
                setTimeout(function() { window.startOnboardingTour({ resumeFromSaved: false }); }, 120);
            }
            return;
        }
        var tocLink = e.target && e.target.closest ? e.target.closest('.help-toc a[href^="#"]') : null;
        if (tocLink) {
            e.preventDefault();
            var id = tocLink.getAttribute('href').slice(1);
            var scrollRoot = document.getElementById('helpModalContent');
            var target = id ? document.getElementById(id) : null;
            if (scrollRoot && target) {
                var rootRect = scrollRoot.getBoundingClientRect();
                var targetRect = target.getBoundingClientRect();
                var nextTop = scrollRoot.scrollTop + (targetRect.top - rootRect.top) - 8;
                if (typeof scrollRoot.scrollTo === 'function') {
                    scrollRoot.scrollTo({ top: Math.max(0, nextTop), behavior: 'smooth' });
                } else {
                    scrollRoot.scrollTop = Math.max(0, nextTop);
                }
            }
        }
    });
}
